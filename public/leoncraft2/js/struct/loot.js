/* ---------------------------------------------------------------------------
   Leoncraft 2 - structures: what is in a chest.

   rollLoot(table, seed) fills one container the way the game's
   LootTable.fill does, from a table in lootdata.js (generated by
   tools/leoncraft2/build_loot.py from the game's own chest and dispenser
   loot tables):

     1. every pool runs in order: its rolls count is drawn, and each roll
        picks one entry by weight (empty entries are part of the weights, and
        a pool with a single entry draws nothing). An entry is an item, an
        empty slot or a whole other table (the trial chamber rewards nest).
     2. an item's count comes from its range, and its flags change the stack:
        damage, a potion, a stew effect, a map, an enchantment.
     3. the container's slots are shuffled, the stacks of more than one item are
        split into smaller ones for as long as there are free slots (the game's
        shuffleAndSplitItems), the lot is shuffled, and each stack goes into the
        next free slot.

   The random source is the same java.util.Random as the structure placement,
   so a loot seed taken from a piece's random (its nextLong) draws what the game
   would draw, apart from the enchantments: which enchantment a book or a tool
   gets needs the whole enchantment list, which this game does not have, so an
   enchanted stack only says how it should be enchanted and nothing is drawn
   for it. A book that is enchanted comes out as an enchanted_book.

   Each stack is { slot, item, count } plus, when they apply:
     ench        { random: true }                  one random enchantment
                 { from: [ids] }                   one, from this list
                 { levels: n, from?: '#tag' }      as at an enchanting table of this level
                 { set: { id: level } }            exactly these
     damage      durability left, 0 to 1 (1 is undamaged)
     potion      the potion id (potion, tipped arrow, splash and lingering)
     map         where the map leads, as the game's destination tag
                 (on_treasure_maps...), with deco (the marker), name (the title's
                 translation key) and zoom. A map whose destination is not found
                 is thrown away by the game; the caller does the same.
     stew        { effect, seconds }               a suspicious stew's effect
     amp         an ominous bottle's amplifier
     instrument  a goat horn's instrument

   Table names may carry "minecraft:" and "chests/". Dispenser tables are named
   dispensers/trial_chambers/chamber and so on, and "jungle_temple_dispenser" is
   one too: those default to nine slots, every other table to 27.

   rollLoot(table, seed, { size, biome }): size is the number of slots and biome
   the biome the chest stands in (a few entries only exist in, or everywhere
   but, one biome; with no biome given the ones that need a biome are left out).
--------------------------------------------------------------------------- */
import { JRand, toLong } from './rand.js?v=18';
import { LOOT } from './lootdata.js?v=18';

const CHEST_SLOTS = 27;
const DISPENSER_SLOTS = 9;
const MAX_NEST = 8;

// the goat horn tags the tables use (the game's own instrument tags)
const HORNS = {
  regular_goat_horns: ['ponder_goat_horn', 'sing_goat_horn', 'seek_goat_horn', 'feel_goat_horn'],
  screaming_goat_horns: ['admire_goat_horn', 'call_goat_horn', 'yearn_goat_horn', 'dream_goat_horn']
};

// "minecraft:chests/village/village_armorer" -> "village/village_armorer", or null when there is no such table
function resolve(name) {
  if (typeof name !== 'string') return null;
  const n = name.replace(/^minecraft:/, '').replace(/^chests\//, '');
  return Object.prototype.hasOwnProperty.call(LOOT, n) ? n : null;
}

export function lootTables() { return Object.keys(LOOT); }
export function hasLoot(table) { return resolve(table) !== null; }

/* --- numbers: Mth.nextInt, Mth.nextFloat and the binomial generator ---------- */
function floatBetween(r, lo, hi) {
  return lo >= hi ? lo : Math.fround(r.nextFloat() * (hi - lo) + lo);
}
function binomial(r, n, p) {
  let k = 0;
  for (let i = 0; i < n; i++) if (r.nextFloat() < p) k++;
  return k;
}
function countOf(r, e) {
  const f = e[4];
  if (f && f.bin) return binomial(r, f.bin[0], f.bin[1]);
  const lo = e[2] === undefined ? 1 : e[2];
  const hi = e[3] === undefined ? lo : e[3];
  return r.between(lo, hi);
}
// Util.shuffle: swap the last place with a random one, then the one before...
function shuffle(list, r) {
  for (let i = list.length; i > 1; i--) {
    const j = r.nextInt(i);
    const t = list[i - 1]; list[i - 1] = list[j]; list[j] = t;
  }
}

/* --- one stack from one entry ------------------------------------------------- */
function makeStack(r, e) {
  const f = e[4];
  const st = { item: e[0], count: 0 };
  if (!f || !f.cl) st.count = countOf(r, e);
  if (f) {
    for (const k in f) {
      const v = f[k];
      switch (k) {
        case 'ench':
          if (v === true) st.ench = { random: true };
          else if (v.levels) {
            st.ench = { levels: r.between(v.levels[0], v.levels[1]) };
            if (v.from) st.ench.from = v.from;
          } else if (v.set) st.ench = { set: Object.assign({}, v.set) };
          else st.ench = { from: v.from.slice() };
          if (st.item === 'book') st.item = 'enchanted_book';
          break;
        case 'damage':
          st.damage = Math.round(floatBetween(r, v[0], v[1]) * 1000) / 1000;
          break;
        case 'map': st.map = v; break;
        case 'deco': st.deco = v; break;
        case 'name': st.name = v; break;
        case 'zoom': st.zoom = v; break;
        case 'potion': st.potion = v; break;
        case 'stew': {
          const pick = v[v.length > 1 ? r.nextInt(v.length) : 0];
          st.stew = [pick[0], Math.round(floatBetween(r, pick[1], pick[2]) * 20)];
          break;
        }
        case 'amp': st.amp = r.between(v[0], v[1]); break;
        case 'instrument': {
          const list = Array.isArray(v) ? v : HORNS[v];
          st.instrument = list ? list[r.nextInt(list.length)] : v;
          break;
        }
        default: break; // chance, biome, notBiome, table, bin, cl are read elsewhere
      }
    }
    if (f.cl) st.count = countOf(r, e);
  }
  return st;
}

/* --- pools and entries -------------------------------------------------------- */
function entryOk(r, f, ctx) {
  if (!f) return true;
  if (f.biome && f.biome.indexOf(ctx.biome) < 0) return false;
  if (f.notBiome && f.notBiome.indexOf(ctx.biome) >= 0) return false;
  if (f.chance !== undefined && !(r.nextFloat() < f.chance)) return false;
  return true;
}

function addOne(r, entries, ctx, out, depth) {
  const valid = [];
  let total = 0;
  for (const e of entries) {
    if (!entryOk(r, e[4], ctx)) continue;
    if (e[1] > 0) { valid.push(e); total += e[1]; }
  }
  if (!valid.length || total <= 0) return;
  let pick = valid[0];
  if (valid.length > 1) {
    let idx = r.nextInt(total);
    for (const e of valid) {
      idx -= e[1];
      if (idx < 0) { pick = e; break; }
    }
  }
  const f = pick[4];
  if (f && f.table !== undefined) {
    if (depth < MAX_NEST) rollTable(r, f.table, ctx, out, depth + 1);
  } else if (pick[0]) {
    out.push(makeStack(r, pick));
  }
}

function rollPool(r, pool, ctx, out, depth) {
  if (pool.chance !== undefined && !(r.nextFloat() < pool.chance)) return;
  const n = pool.bin ? binomial(r, pool.bin[0], pool.bin[1]) : r.between(pool.rolls[0], pool.rolls[1]);
  for (let i = 0; i < n; i++) addOne(r, pool.entries, ctx, out, depth);
}

function rollTable(r, name, ctx, out, depth) {
  const pools = LOOT[name];
  if (!pools) return;
  for (const pool of pools) rollPool(r, pool, ctx, out, depth);
}

/* --- into the container ------------------------------------------------------- */
// the game's shuffleAndSplitItems: break stacks up while there are slots to spare
function splitAndShuffle(stacks, free, r) {
  const keep = [];
  const many = [];
  for (const s of stacks) {
    if (s.count > 1) many.push(s);
    else if (s.count === 1) keep.push(s);
  }
  while (free - keep.length - many.length > 0 && many.length > 0) {
    const s = many.splice(r.between(0, many.length - 1), 1)[0];
    const off = r.between(1, s.count >> 1);
    const piece = Object.assign({}, s, { count: off });
    s.count -= off;
    if (s.count > 1 && r.nextBoolean()) many.push(s); else keep.push(s);
    if (piece.count > 1 && r.nextBoolean()) many.push(piece); else keep.push(piece);
  }
  for (const s of many) keep.push(s);
  shuffle(keep, r);
  return keep;
}

// the contents of one container, as an array of stacks sorted by slot
export function rollLoot(table, seed, opts) {
  const name = resolve(table);
  if (name === null) return [];
  const o = opts || {};
  const size = o.size > 0 ? Math.floor(o.size)
    : (name.indexOf('dispenser') >= 0 ? DISPENSER_SLOTS : CHEST_SLOTS);
  const r = new JRand(toLong(seed));
  const ctx = { biome: String(o.biome || '').replace(/^minecraft:/, '') };

  const rolled = [];
  rollTable(r, name, ctx, rolled, 0);

  const slots = [];
  for (let i = 0; i < size; i++) slots.push(i);
  shuffle(slots, r);
  const stacks = splitAndShuffle(rolled, slots.length, r);

  const out = [];
  for (const s of stacks) {
    if (!slots.length) break;
    out.push(Object.assign({ slot: slots.pop() }, s));
  }
  out.sort((a, b) => a.slot - b.slot);
  return out;
}
