"""
Leoncraft 2 - recipe book unlocks build.

Writes public/leoncraft2/js/recipeunlocks.js: for each crafting recipe's
result, the items that unlock it in the recipe book (the game's recipe
advancements, data/minecraft/advancement/recipes/: carrying any of the
items its inventory_changed criteria name, tags opened into item names),
'@water' for the boats (standing in water also unlocks them), and the
recipes unlocked from the start (the crafting table). Recipes that make the
same item share one list. Only the facts are kept (which item unlocks
what); nothing else of the jar is copied.

Input: the player's own Minecraft client jar, read locally.

  python tools/leoncraft2/build_recipe_unlocks.py <client jar>
"""
import json, os, sys, zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'public', 'leoncraft2', 'js', 'recipeunlocks.js')
strip = lambda s: s.replace('minecraft:', '') if isinstance(s, str) else s
CRAFTING = ('minecraft:crafting_shaped', 'minecraft:crafting_shapeless', 'minecraft:crafting_transmute')


def main():
    z = zipfile.ZipFile(sys.argv[1])
    names = set(z.namelist())

    def tag(name, depth=0):
        p = 'data/minecraft/tags/item/%s.json' % strip(name).lstrip('#')
        if p not in names or depth > 6:
            return []
        out = []
        for v in json.loads(z.read(p))['values']:
            v = v if isinstance(v, str) else v['id']
            out += tag(v, depth + 1) if v.startswith('#') else [strip(v)]
        return out

    def items_of(v):
        if isinstance(v, list):
            return [x for e in v for x in items_of(e)]
        return tag(v) if v.startswith('#') else [strip(v)]

    unlocks, start = {}, []
    for n in sorted(names):
        if not (n.startswith('data/minecraft/advancement/recipes/') and n.endswith('.json')):
            continue
        a = json.loads(z.read(n))
        rec = (a.get('rewards') or {}).get('recipes') or []
        if not rec:
            continue
        got, now = [], False
        for c in a['criteria'].values():
            t = c['trigger']
            if t == 'minecraft:inventory_changed':
                for it in c.get('conditions', {}).get('items', []):
                    if 'items' in it:
                        got += items_of(it['items'])
            elif t == 'minecraft:enter_block' and strip(c.get('conditions', {}).get('block')) == 'water':
                got.append('@water')
            elif t == 'minecraft:tick':
                now = True
        for rid in rec:
            p = 'data/minecraft/recipe/%s.json' % strip(rid)
            if p not in names:
                continue
            r = json.loads(z.read(p))
            if r['type'] not in CRAFTING or 'result' not in r:
                continue
            res = strip(r['result']['id'] if isinstance(r['result'], dict) else r['result'])
            if now:
                start.append(res)
            lst = unlocks.setdefault(res, [])
            for g in got:
                if g not in lst:
                    lst.append(g)

    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* Generated by tools/leoncraft2/build_recipe_unlocks.py from the game\'s recipe advancements:\n'
                '   the items that unlock the recipes making each item in the recipe book, and those known from the start. */\n')
        f.write('export const UNLOCKS = ' + json.dumps(unlocks, separators=(',', ':'), sort_keys=True) + ';\n')
        f.write('export const START = ' + json.dumps(sorted(set(start))) + ';\n')
    print('results', len(unlocks), 'start', start, 'bytes', os.path.getsize(OUT))


if __name__ == '__main__':
    main()
